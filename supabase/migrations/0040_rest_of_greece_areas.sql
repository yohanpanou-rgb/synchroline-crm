-- (ΝΙΚΑΙΑ/Λάρισας, ΝΑΥΠΛΙΟ/Αττικής -- data error, ΘΕΡΜΗ bare) ώστε να μην
-- ξαναδημιουργηθεί το πρόβλημα λάθος-πόλης.
update doctors d
set area_id = a.id
from areas a
where d.area_id is null
  and d.region is not null
  and not (d.region = 'ΝΙΚΑΙΑ' and d.nomos = 'ΛΑΡΙΣΑΣ')
  and not (d.region = 'ΝΑΥΠΛΙΟ' and d.nomos = 'ΑΤΤΙΚΗΣ')
  and d.region <> 'ΘΕΡΜΗ'
  and (
    immutable_unaccent(upper(trim(d.region))) = a.canonical_name
    or immutable_unaccent(upper(trim(d.region))) = any(a.aliases)
  );

